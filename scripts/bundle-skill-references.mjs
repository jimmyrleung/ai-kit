#!/usr/bin/env node
// --check is read-only. --write regenerates owned copies after a complete preflight.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '<!-- Generated by bundle-skill-references;';
// Collect destination prefixes, not complete Markdown links: optional titles must never
// decide whether a dependency survives. This conservatively retains a recognized path
// even if its trailing title/closing syntax is malformed; it is not a Markdown validator.
// Both inline links and reference definitions may put the destination on the next line.
const LINK = /\]\([ \t]*(?:\r?\n[ \t]*)?(<[^>\r\n]+>|[^\s)]+)|^[ \t]{0,3}\[[^\]\r\n]+\]:[ \t]*(?:\r?\n[ \t]*)?(<[^>\r\n]+>|[^\s]+)/gm;
const destinationOf = (inline, definition) => (inline || definition).replace(/^<|>$/g, '');
const HASH = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const posix = (value) => value.split(path.sep).join('/');
const inside = (root, file) => file === root || file.startsWith(root + path.sep);

function plainFile(file, boundary) {
  if (!inside(boundary, fs.realpathSync(file)) || !fs.statSync(file).isFile()) {
    throw new Error(`reference is not a file inside its source root: ${file}`);
  }
  return fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

function documents(root) {
  const docs = path.join(root, 'docs');
  const files = fs.readdirSync(path.join(docs, 'contracts')).sort()
    .filter((name) => name.endsWith('.md')).map((name) => path.join(docs, 'contracts', name));
  files.push(path.join(docs, 'provider-capabilities.md'), path.join(docs, 'output-filename-contract.md'));
  const sources = new Map();
  for (const file of files) {
    const name = path.basename(file);
    if (sources.has(name)) throw new Error(`duplicate shared reference name: ${name}`);
    sources.set(name, { file, text: plainFile(file, fs.realpathSync(docs)) });
  }
  return sources;
}

function markdownFiles(dir, excluded) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (file === excluded) continue;
    // Bundled skill contents must not depend on links to files outside their folder.
    if (entry.isSymbolicLink()) throw new Error(`linked skill dependency needs a local copy: ${file}`);
    if (entry.isDirectory()) files.push(...markdownFiles(file, excluded));
    else if (entry.isFile() && entry.name.endsWith('.md')) files.push(file);
  }
  return files.sort();
}

function checkOutputPath(skill, output) {
  // Refuse symlink/junction components before writing or checking generated content.
  let current = skill;
  for (const part of path.relative(skill, output).split(path.sep)) {
    current = path.join(current, part);
    let info;
    try { info = fs.lstatSync(current); } catch (error) { if (error.code === 'ENOENT') break; throw error; }
    if (info.isSymbolicLink() || !inside(fs.realpathSync(skill), fs.realpathSync(current))) {
      throw new Error(`generated output uses a link: ${current}`);
    }
  }
}

export function bundleSkillReferences(root = ROOT, { write = false } = {}) {
  root = fs.realpathSync(root);
  const result = { files: [], findings: [], written: [], retired: [] };
  const plans = [];
  try {
    const sources = documents(root);
    const byPath = new Map([...sources].map(([name, source]) => [source.file, name]));
    const skills = path.join(root, 'skills');
    for (const entry of fs.readdirSync(skills, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const skill = path.join(skills, entry.name);
      if (!(entry.isDirectory() || entry.isSymbolicLink()) || !fs.statSync(skill).isDirectory()) continue;
      const output = path.join(skill, 'references', 'shared');
      checkOutputPath(skill, output);
      const requested = new Set();
      for (const file of markdownFiles(skill, output)) {
        const text = fs.readFileSync(file, 'utf8');
        for (const match of text.matchAll(LINK)) {
          const target = destinationOf(match[1], match[2]).split('#')[0];
          if (!target || /^(?:[a-z]+:|\/)/i.test(target)) continue;
          const resolved = path.resolve(path.dirname(file), target);
          if (inside(output, resolved)) {
            if (path.dirname(resolved) !== output || !sources.has(path.basename(resolved))) {
              throw new Error(`unknown bundled reference in ${file}: ${target}`);
            }
            requested.add(path.basename(resolved));
          } else if (byPath.has(resolved) || target.includes('../../docs/')) {
            throw new Error(`external shared reference in ${file}: ${target}; use references/shared/`);
          }
        }
      }
      const expected = new Map();
      function visit(name) {
        if (expected.has(name)) return;
        expected.set(name, ''); // Cycle guard; source contents are emitted once per skill.
        const source = sources.get(name);
        if (!source) throw new Error(`missing shared source: ${name}`);
        const text = source.text.replace(LINK, (match, inline, definition) => {
          const destination = destinationOf(inline, definition);
          if (/^(?:[a-z]+:|\/|#)/i.test(destination)) {
            if (destination.startsWith('/')) throw new Error(`absolute source link in ${source.file}: ${destination}`);
            return match;
          }
          const [relative, ...fragment] = destination.split('#');
          const child = byPath.get(path.resolve(path.dirname(source.file), relative));
          if (!child) throw new Error(`unbundled source link in ${source.file}: ${destination}`);
          visit(child);
          return match.replace(destination, child + (fragment.length ? '#' + fragment.join('#') : ''));
        });
        const origin = posix(path.relative(root, source.file));
        expected.set(name, `${HEADER} source: ${origin}; sha256: ${HASH(source.text)}.\nEdit the maintained source in ai-kit and run npm run build:skill-references. -->\n\n${text}`);
      }
      for (const name of [...requested].sort()) visit(name);
      const old = fs.existsSync(output) ? fs.readdirSync(output).sort() : [];
      if ((expected.size || old.length) && !inside(root, fs.realpathSync(skill))) {
        throw new Error(`external skill source is not managed by this generator: ${skill}`);
      }
      for (const name of old) {
        const file = path.join(output, name);
        checkOutputPath(skill, file);
        if (!fs.statSync(file).isFile() || !fs.readFileSync(file, 'utf8').startsWith(HEADER)) {
          throw new Error(`unowned content in generated directory: ${file}`);
        }
        if (!expected.has(name)) plans.push({ file, retire: true });
      }
      for (const [name, text] of [...expected].sort(([a], [b]) => a.localeCompare(b))) {
        const file = path.join(output, name);
        result.files.push(posix(path.relative(root, file)));
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) plans.push({ file, text });
      }
    }
  } catch (error) {
    result.findings.push({ code: 'skill-reference-input', file: 'skills', message: error.message });
    return result;
  }
  for (const plan of plans) {
    const file = posix(path.relative(root, plan.file));
    if (!write) {
      result.findings.push({ code: 'skill-reference-drift', file, message: plan.retire ? 'unused generated copy' : 'generated reference is missing or stale' });
    } else if (plan.retire) {
      fs.unlinkSync(plan.file);
      result.retired.push(file);
    } else {
      fs.mkdirSync(path.dirname(plan.file), { recursive: true });
      fs.writeFileSync(plan.file, plan.text, 'utf8');
      result.written.push(file);
    }
  }
  return result;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  try {
    const args = process.argv.slice(2);
    if (args.length !== 1 || !['--check', '--write'].includes(args[0])) throw new Error('Usage: node scripts/bundle-skill-references.mjs --check|--write');
    const result = bundleSkillReferences(ROOT, { write: args[0] === '--write' });
    for (const item of result.findings) console.error(`${item.code}: ${item.file}: ${item.message}`);
    console.log(`Shared references: ${result.files.length}; written: ${result.written.length}; retired: ${result.retired.length}; findings: ${result.findings.length}`);
    process.exitCode = result.findings.length ? 1 : 0;
  } catch (error) {
    console.error(error.message);
    process.exitCode = 2;
  }
}
